    // 그것을 여전히 같은 방식으로 그리는지는 **아무도 증명하지 않았고**, 그래서
    // 그리기 코드의 리팩토링은 전부 diff 를 꼼꼼히 읽는 것에 기대고 있었다.
    //
    // 이 함수는 정해진 시드·시점·각도 묶음을 3D 화면, 탑다운 화면, 터미널 조립기에
