    // 어느 것도 시간이나 난수를 들고 있지 않다.
    //
    // **이 값이 바뀌었다면 화면이 바뀐 것이다.** 그게 요점이다. 리팩토링이 이 숫자를
    // 움직였으면 동작을 되돌리든가, 플레이어에게 무엇이 다르게 보이게 되는지를
    // 소리 내어 말하든가 둘 중 하나다.
